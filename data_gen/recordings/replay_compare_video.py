"""Side-by-side video: the recorded episode vs an open-loop action replay of it.

LEFT   what the recording actually contains. Every frame is produced by restoring
       the recorded simulator state, which round-trips bit-exactly, so this panel
       IS the demonstration.
RIGHT  the same episode regenerated by restoring only frame 0 and then re-running
       physics with the recorded actions.

The HUD reports, per frame, how far the right panel has drifted from the left,
and marks the frame where the hand first touches a task object -- measured to be
the point where a micrometre-scale difference is rescaled into a millimetre-scale
one.

    python -m data_gen.recordings.replay_compare_video data/teleop_lerobot/NutBoltTurnNut-Sharpa-v1 \
        --episodes 5 --out videos/replay_compare

Accepts a certified LeRobot dataset root (uses its replay/source_* sidecars), a
pending session directory, or a single pending episode directory.
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import pathlib
from typing import Any

import numpy as np


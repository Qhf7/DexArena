from data_gen.recordings.episode_store import restore_seed

def _episode_dirs(target: pathlib.Path, limit: int) -> list[pathlib.Path]:
    """Every payload directory under `target`, newest-agnostic, capped at `limit`."""
    if (target / "meta" / "info.json").exists():          # LeRobot dataset root
        found = sorted(target.glob("replay/source_*"))
        if not found:
            raise SystemExit(
                f"{target} has no replay/source_* sidecars; point at the pending "
                "session directory instead"
            )
    elif (target / "episode.npz").exists():               # one pending episode
        found = [target]
    else:                                                 # a pending session
        found = sorted(target.glob("episode_*"))
    if not found:
        raise SystemExit(f"no episodes found under {target}")
    return found[:limit] if limit > 0 else found


def _load(ep_dir: pathlib.Path) -> dict[str, Any]:
    import pickle

    meta = json.loads((ep_dir / "meta.json").read_text())
    with np.load(ep_dir / "episode.npz", allow_pickle=True) as z:
        actions = np.asarray(z["actions"])
        success = np.asarray(z["success"]).reshape(-1) if "success" in z.files else None
    with open(ep_dir / "raw_states.pkl", "rb") as fh:
        raw = pickle.load(fh)
    return {"meta": meta, "actions": actions, "success": success, "raw": raw, "dir": ep_dir}


def _shrink_render_camera(identity: dict[str, Any], res: int) -> dict[str, Any]:
    """Render at `res` instead of the recorded 1280x720, purely for speed."""
    identity = dict(identity)
    kwargs = identity.get("env_kwargs") or "{}"
    kwargs = json.loads(kwargs) if isinstance(kwargs, str) else dict(kwargs)
    kwargs["human_render_camera_configs"] = {"width": res, "height": res}
    identity["env_kwargs"] = kwargs
    return identity


# A representation parked outside the workspace. Park heights are signed in this
# repo -- Screwing parks its free nut at z = -5.0, CabinetPour parks its cap twin
# at z = +5.0 -- so the test has to be on |z|, not z.
PARKED_ABS_Z = 1.0


def _compare_bodies(a: Any, b: Any, robot_key: str) -> dict[str, Any]:
    """Compare the task bodies, keeping three different failures apart.

    A raw max-over-actors number conflates them and is unreadable:

    * `object_mm`   real drift of a body that is IN PLAY in both runs.
    * `swap`        the same body is parked out of the world in one run and not
                    the other -- a REPRESENTATION SWITCH (the A/B twin swap), so
                    the two runs are on different task branches. This shows up
                    as metres and is not drift at all.
    * `joint_rad`   task articulations (a cabinet door, a threaded nut): several
                    families have no free actor at all and are invisible to an
                    actors-only metric.
    """
    object_mm, swap, joint_rad = 0.0, [], 0.0
    for name in b.get("actors", {}):
        if name in ("table-workspace", "ground") or name not in a.get("actors", {}):
            continue
        x = np.asarray(a["actors"][name]).reshape(-1)
        y = np.asarray(b["actors"][name]).reshape(-1)
        parked_a, parked_b = abs(x[2]) > PARKED_ABS_Z, abs(y[2]) > PARKED_ABS_Z
        if parked_a != parked_b:
            swap.append(name)
            continue
        if parked_a and parked_b:
            continue
        object_mm = max(object_mm, float(np.abs(x[:3] - y[:3]).max()) * 1000.0)
    for name in b.get("articulations", {}):
        if name == robot_key or name not in a.get("articulations", {}):
            continue
        x = np.asarray(a["articulations"][name]).reshape(-1)
        y = np.asarray(b["articulations"][name]).reshape(-1)
        # A PARKED articulation representation (e.g. the swapped-out threaded nut
        # at |z|=5) is out of play; old recordings additionally carry the F1
        # ground-penetration garbage (qpos +-4pi, qvel 1e17) in exactly that
        # block, which would swamp the task-joint metric with nonsense.
        if abs(y[2]) > PARKED_ABS_Z or abs(x[2]) > PARKED_ABS_Z:
            continue
        if not (np.isfinite(x).all() and np.isfinite(y).all()):
            continue
        dof = (y.shape[0] - 13) // 2
        if dof > 0:
            joint_rad = max(joint_rad, float(np.abs(x[13:13 + dof] - y[13:13 + dof]).max()))
    return {"object_mm": object_mm, "swap": swap, "joint_rad": joint_rad}


def _robot_error(a: Any, b: Any, key: str, dof: int) -> float:
    x = np.asarray(a["articulations"][key]).reshape(-1)
    y = np.asarray(b["articulations"][key]).reshape(-1)
    return float(np.abs(x[13:13 + dof] - y[13:13 + dof]).max())


def _hand_touching_object(env, robot_links: set[str], object_names: set[str]) -> int:
    """Contacts between a robot link and a task body.

    Actor entities are scene-prefixed (`scene-0_bolt`) so the prefix is stripped
    before an EXACT name match. Substring matching is a measured trap: PartNet
    articulations use short link names (`base`, `link_0`) that are substrings of
    the robot's own `mobile_base_link_*`, so a robot SELF-contact counted as
    hand-object contact from step 1 (DoorOpen/BottlePickPlace)."""
    import re

    hits = 0
    for contact in env.unwrapped.scene.get_contacts():
        n0 = contact.bodies[0].entity.name
        n1 = contact.bodies[1].entity.name
        for a, b in ((n0, n1), (n1, n0)):
            a_core = re.sub(r"^scene-\d+_", "", a)
            if (
                a_core in object_names
                and a not in robot_links and a_core not in robot_links
                and b in robot_links
            ):
                hits += 1
                break
    return hits


def _warm_up_from_frame0(env, raw0: dict[str, Any], robot_key: str, hold_steps: int) -> None:
    """The zero-error replay recipe.

    A restore writes exact poses/velocities but leaves the engine COLD: the contact
    report is empty until the first simulate() rebuilds pairs/manifolds/impulses.
    Feeding action[0] into that cold step seeds a 1-ulp difference that the joint
    drive's threshold nonlinearities later quantize into 1e-5..1e-2 rad. Measured
    fix, in order:

      1. hold the frame-0 joint targets for `hold_steps` (1 suffices) -> cold->warm;
      2. re-pin free actors to the recorded frame-0 state (a resting body creeps
         ~1.9 um per held step in BOTH runs; the hold steps are extra in the replay);
      3. write back ONLY the task-state counters (they advanced during the hold;
         physics-neutral, verified 0.0) and re-align the episode clock.

    With matching task code this made whole episodes bit-exact (ScrewingTurn 6/6,
    NutPickPlace 3/3, incl. the success step).
    """
    import torch
    from mani_skill.utils.structs.pose import Pose as MSPose

    base = env.unwrapped
    art = base.scene.articulations[robot_key]
    joint_names = [j.name for j in art.get_active_joints()]
    q0 = art.get_qpos().detach().cpu().numpy().reshape(-1)
    order = [
        j.name
        for controller in base.agent.controller.controllers.values()
        for j in controller.joints
    ]
    hold = torch.as_tensor(
        np.asarray([q0[joint_names.index(n)] for n in order], np.float32)
    )[None]
    for _ in range(max(1, hold_steps)):
        env.step(hold)
    for name, actor in base.scene.actors.items():
        if getattr(actor, "px_body_type", None) != "dynamic":
            continue
        if name not in raw0.get("actors", {}):
            continue
        v = torch.as_tensor(
            np.asarray(raw0["actors"][name]), device=base.device
        ).reshape(1, -1)
        actor.set_pose(MSPose.create(v[:, :7]))
        actor.set_linear_velocity(v[:, 7:10])
        actor.set_angular_velocity(v[:, 10:13])
    task_keys = [k for k in raw0 if k.endswith("_task_state") or k == "cap_screw"]
    if task_keys:
        base.set_state_dict(
            {
                k: torch.as_tensor(np.asarray(raw0[k]), device=base.device)
                for k in task_keys
            }
        )
    context = raw0.get("__recording_context__")
    if context is not None and getattr(base, "_elapsed_steps", None) is not None:
        elapsed = int(np.asarray(context["elapsed_steps"]).reshape(-1)[0])
        base._elapsed_steps.copy_(
            torch.as_tensor(
                [elapsed],
                device=base._elapsed_steps.device,
                dtype=base._elapsed_steps.dtype,
            )
        )


def _frame(env, res: int) -> np.ndarray:
    """One RGB frame, whichever device the renderer returned it on."""
    img = env.render()
    if hasattr(img, "detach"):
        img = img.detach().cpu().numpy()
    return np.asarray(img).reshape(res, res, 3).astype(np.uint8)


def _panel(frame: np.ndarray, title: str, lines: list[str], colour) -> np.ndarray:
    import cv2

    out = frame.copy()
    cv2.rectangle(out, (0, 0), (out.shape[1], 28), (0, 0, 0), -1)
    cv2.putText(out, title, (8, 20), cv2.FONT_HERSHEY_SIMPLEX, 0.55, colour, 1, cv2.LINE_AA)
    y = out.shape[0] - 8 - 16 * (len(lines) - 1)
    for text in lines:
        cv2.putText(out, text, (8, y), cv2.FONT_HERSHEY_SIMPLEX, 0.42,
                    (255, 255, 255), 1, cv2.LINE_AA)
        y += 16
    return out


def render_episode(ep: dict[str, Any], out_path: pathlib.Path, res: int,
                   max_steps: int, stride: int,
                   hold_steps: int = 1, warmup: bool = True) -> dict[str, Any]:
    import cv2
    import imageio.v2 as imageio
    import torch

    from data_gen.recordings import replay_recording as RR

    meta = ep["meta"]
    identity = _shrink_render_camera(meta["identity_manifest"], res)
    raw, actions = ep["raw"], ep["actions"]
    steps = len(actions) if max_steps <= 0 else min(max_steps, len(actions))

    env = RR._make_env(identity)
    env.reset(seed=restore_seed(meta, default=0))
    base = env.unwrapped
    robot_key = next(k for k in raw[0]["articulations"] if "panda" in k)
    dof = (np.asarray(raw[0]["articulations"][robot_key]).reshape(-1).shape[0] - 13) // 2
    robot_links = {l.name for l in base.agent.robot.get_links()}
    object_names = set(raw[0].get("actors", {})) - {"table-workspace", "ground"}
    # Several families (DoorOpen, Juice) have no free actor at all -- the object
    # manipulated is an articulation. Add its link names, or the
    # contact probe silently reports "never touched".
    for art_name, art in base.scene.articulations.items():
        if art_name == robot_key:
            continue
        for link in art.get_links() or []:
            object_names.add(str(link.name))

    # ---- pass A: the recording, replayed by restoring each recorded state ----
    left: list[np.ndarray] = []
    for t in range(0, steps + 1, stride):
        RR._set_raw_state(env, raw[t])
        left.append(_frame(env, res))

    # ---- pass B: open-loop action replay from frame 0 ------------------------
    env.close()
    env = RR._make_env(identity)
    env.reset(seed=restore_seed(meta, default=0))
    base = env.unwrapped
    RR._set_raw_state(env, raw[0])
    if warmup:
        _warm_up_from_frame0(env, raw[0], robot_key, hold_steps)
    right: list[np.ndarray] = [_frame(env, res)]
    obj_err, rob_err, touch = [0.0], [0.0], [0]
    joint_err, swaps = [0.0], [[]]
    replay_success_step: int | None = None
    for t in range(steps):
        _o, _r, _te, _tr, info = env.step(
            torch.as_tensor(actions[t], dtype=torch.float32)[None]
        )
        if replay_success_step is None:
            flag = info.get("success")
            if flag is not None:
                value = flag.detach().cpu() if hasattr(flag, "detach") else flag
                if bool(np.asarray(value).reshape(-1)[0]):
                    replay_success_step = t
        got = RR._current_raw_state(env)
        cmp = _compare_bodies(got, raw[t + 1], robot_key)
        obj_err.append(cmp["object_mm"])
        joint_err.append(cmp["joint_rad"])
        swaps.append(cmp["swap"])
        rob_err.append(_robot_error(got, raw[t + 1], robot_key, dof))
        touch.append(_hand_touching_object(env, robot_links, object_names))
        if (t + 1) % stride == 0:
            right.append(_frame(env, res))
    env.close()

    first_touch = next((i for i, v in enumerate(touch) if v > 0), None)
    first_mm = next((i for i, v in enumerate(obj_err) if v > 1.0), None)
    first_swap = next((i for i, v in enumerate(swaps) if v), None)
    # warm-up efficacy witness, valid regardless of code drift: with the warm-up
    # the robot must stay (near) bit-exact until first hand-object contact; a
    # COLD replay instead drifts in FREE SPACE (~step 91 stiction signature).
    first_robot = next((i for i, v in enumerate(rob_err) if v > 1e-4), None)

    n = min(len(left), len(right))
    writer = imageio.get_writer(out_path, fps=max(1, round(20 / stride)), macro_block_size=1)
    for i in range(n):
        t = i * stride
        k = min(t, len(obj_err) - 1)
        oe, re_, je = obj_err[k], rob_err[k], joint_err[k]
        touching = touch[min(t, len(touch) - 1)] > 0
        sw = swaps[k]
        lo = _panel(left[i], "RECORDED  (state restore = the demonstration)",
                    [f"step {t}/{steps}"], (120, 255, 120))
        lines = [f"object drift {oe:8.3f} mm",
                 f"joint  drift {je:9.2e} rad",
                 f"robot  drift {re_:9.2e} rad",
                 ("HAND TOUCHING OBJECT" if touching else "object untouched"),
                 (f"TASK SUCCESS @ step {replay_success_step}"
                  if replay_success_step is not None and t >= replay_success_step
                  else "task not yet succeeded")]
        if sw:
            lines.append("!! REPRESENTATION SWITCH DIFFERS: " + ",".join(sw))
        ro = _panel(right[i], "ACTION REPLAY  (frame 0 + recorded actions)", lines,
                    (80, 160, 255) if touching else (120, 200, 255))
        sep = np.full((lo.shape[0], 4, 3), 40, np.uint8)
        writer.append_data(np.concatenate([lo, sep, ro], axis=1))
    writer.close()

    return {
        "episode": ep["dir"].name,
        "session": ep["dir"].parent.name,
        "env_id": meta.get("env_id"),
        "steps": steps,
        "first_hand_object_contact": first_touch,
        "first_robot_drift_step": first_robot,
        "robot_drift_before_contact": (
            first_robot is not None and first_touch is not None and first_robot < first_touch
        ),
        "first_step_over_1mm": first_mm,
        "first_representation_switch_mismatch": first_swap,
        "object_drift_at_contact_mm": (obj_err[first_touch]) if first_touch else 0.0,
        "final_object_drift_mm": obj_err[min(steps, len(obj_err) - 1)],
        "final_joint_drift_rad": joint_err[min(steps, len(joint_err) - 1)],
        "final_robot_drift_rad": rob_err[min(steps, len(rob_err) - 1)],
        # read from the recording itself (in the exported corpus success fires on
        # the LAST action -- auto-segment cuts at the latch instant, 177/177)
        "recorded_task_success": (
            bool(np.asarray(ep["success"]).any()) if ep.get("success") is not None else None
        ),
        "recorded_success_step": (
            int(np.flatnonzero(np.asarray(ep["success"]))[0])
            if ep.get("success") is not None and np.asarray(ep["success"]).any()
            else None
        ),
        "replay_success_step": replay_success_step,
        "replay_task_success": replay_success_step is not None,
        "warmup": bool(warmup),
        "hold_steps": int(hold_steps) if warmup else 0,
        "video": str(out_path),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("target", type=pathlib.Path)
    ap.add_argument("--episodes", type=int, default=5, help="0 = all")
    ap.add_argument("--out", type=pathlib.Path, default=pathlib.Path("videos/replay_compare"))
    ap.add_argument("--res", type=int, default=448)
    ap.add_argument("--max-steps", type=int, default=0, help="0 = whole episode")
    ap.add_argument("--stride", type=int, default=1, help="render every Nth frame")
    ap.add_argument("--hold-steps", type=int, default=1,
                    help="warm-up hold steps after the frame-0 restore (1 suffices)")
    ap.add_argument("--no-warmup", action="store_true",
                    help="replay the OLD way (cold restore, no re-pin/clock fix) "
                         "to demonstrate the difference the recipe makes")
    args = ap.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    rows = []
    dirs = _episode_dirs(args.target, args.episodes)
    print(f"[replay-compare] {len(dirs)} episode(s) -> {args.out}", flush=True)
    for i, d in enumerate(dirs, 1):
        ep = _load(d)
        name = f"{d.parent.name}__{d.name}.mp4".replace("/", "_")
        print(f"  [{i}/{len(dirs)}] {d.parent.name}/{d.name} "
              f"({len(ep['actions'])} steps) ...", flush=True)
        row = render_episode(ep, args.out / name, args.res, args.max_steps, args.stride,
                             hold_steps=args.hold_steps, warmup=not args.no_warmup)
        rows.append(row)
        print(f"        contact@{row['first_hand_object_contact']}  "
              f">1mm@{row['first_step_over_1mm']}  "
              f"final drift {row['final_object_drift_mm']:.2f} mm  "
              f"success replay@{row['replay_success_step']} "
              f"rec@{row['recorded_success_step']} -> {name}", flush=True)

    total = len(rows)
    state_ok = sum(1 for r in rows if r.get("recorded_task_success"))
    action_ok = sum(1 for r in rows if r.get("replay_task_success"))
    print(f"[replay-compare] SUCCESS RATE  state(recorded demo) {state_ok}/{total} "
          f"({state_ok / max(total, 1):.0%})   action(open-loop replay) {action_ok}/{total} "
          f"({action_ok / max(total, 1):.0%})", flush=True)

    csv_path = args.out / "summary.csv"
    with open(csv_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    print(f"[replay-compare] summary -> {csv_path}", flush=True)


if __name__ == "__main__":
    main()
